# Generates build_secrets.h (in the build dir, never committed) with optional
# build-time settings. Read from the environment first, then from
# secrets.env (KEY=VALUE lines).
#   WIFI_SSID / WIFI_PASS  - network to join when stored credentials don't work
#   OTA_PASS               - password protecting /update (user "admin")
#   CLOCK_TZ               - POSIX TZ string (default: UK time)
Import("env")
import os


def c_string(v):
    # UTF-8 passes through as-is; quotes, backslashes and control characters are
    # escaped. Octal escapes are always 3 digits, so a following digit can't join.
    out = []
    for ch in v:
        if ch in '"\\':
            out.append("\\" + ch)
        elif ord(ch) < 0x20 or ord(ch) == 0x7F:
            out.append("\\%03o" % ord(ch))
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


KEYS = ("WIFI_SSID", "WIFI_PASS", "OTA_PASS", "CLOCK_TZ")

values = {}
path = os.path.join(env.subst("$PROJECT_DIR"), "secrets.env")
if os.path.exists(path):
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            k, v = line.split("=", 1)
            v = v.strip()
            if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
                v = v[1:-1]
            values[k.strip()] = v
for k in KEYS:
    if os.environ.get(k):
        values[k] = os.environ[k]

out_dir = os.path.join(env.subst("$BUILD_DIR"), "generated")
os.makedirs(out_dir, exist_ok=True)
lines = ["// Generated by scripts/secrets.py - do not edit, do not commit.", "#pragma once"]
for k in KEYS:
    if values.get(k):
        lines.append("#define %s %s" % (k, c_string(values[k])))
content = "\n".join(lines) + "\n"
out = os.path.join(out_dir, "build_secrets.h")
# Only rewrite on change so unchanged secrets don't force a rebuild.
if not os.path.exists(out) or open(out, encoding="utf-8").read() != content:
    with open(out, "w", encoding="utf-8") as f:
        f.write(content)
env.Append(CPPPATH=[out_dir])

print("secrets: " + (", ".join(k for k in KEYS if values.get(k)) or "none set"))
